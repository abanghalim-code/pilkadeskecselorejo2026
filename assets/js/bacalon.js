// Ambil semua bacalon berdasarkan desa dan urutkan berdasarkan nomor urut.
function getBacalonByDesa(desa) {
  return bacalon
    .filter(item => item.desa === desa)
    .sort((a, b) => Number(a.no_urut) - Number(b.no_urut));
}

// Ambil satu bacalon berdasarkan ID permanen.
function getBacalonById(id) {
  return bacalon.find(item => item.id === id);
}

// Daftar desa yang tersedia.
function getDesaBacalon() {
  return [...new Set(bacalon.map(item => item.desa))];
}
